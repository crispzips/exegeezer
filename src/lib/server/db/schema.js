// ---------------------------------------------------------------------------
// Texts. A paragraph or a section is a piece of content in its own right and can
// appear in any number of texts (remixes, and later commentaries, glosses...).
// A text is an assemblage of them: `text_item` arranges them, one row per place in
// the text, numbered from 0 in document order. What is specific to a place rather
// than to the content lives on that row: a section's header `level` (1-6) and
// whether it is the autogenerated Frontmatter. A section runs until the next
// section of the same or a shallower level, so the ordered rows are all it takes to
// rebuild a text's hierarchy.
// ---------------------------------------------------------------------------

export const text_ = pgTable(
  "text",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // null = not tied to an account
    userId: text("user_id").references(() => user.id, { onDelete: "cascade" }),
    // the persona the text is written as (new texts get their owner's "self")
    personaId: uuid("persona_id").references(() => persona.id, { onDelete: "set null" }),
    title: text("title").notNull().default("Untitled"),
    // 'original' or 'commentary'
    type: text("type").notNull().default("original"),
    // 'idea' | 'draft' | 'under review' | 'published'; new texts start as drafts
    productionStatus: text("production_status").notNull().default("draft"),
    // 'private' | 'public'; chosen by the user when the text is created
    visibility: text("visibility").notNull().default("private"),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .defaultNow()
      .$onUpdate(() => /* @__PURE__ */ new Date())
      .notNull(),
  },
  (table) => [
    index("text_userId_idx").on(table.userId),
    index("text_personaId_idx").on(table.personaId),
    check("text_production_status_check", sql`${table.productionStatus} in ('idea', 'draft', 'under review', 'published')`),
    check("text_visibility_check", sql`${table.visibility} in ('private', 'public')`),
  ],
);

// A text can be by several personae. `text_author` lists them in order (position 0 is the first
// author); `text.persona_id` mirrors the first author so older code that reads one author keeps working.
export const textAuthor = pgTable(
  "text_author",
  {
    textId: uuid("text_id")
      .notNull()
      .references(() => text_.id, { onDelete: "cascade" }),
    personaId: uuid("persona_id")
      .notNull()
      .references(() => persona.id, { onDelete: "cascade" }),
    position: integer("position").notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.textId, table.personaId] }),
    index("text_author_personaId_idx").on(table.personaId),
  ],
);

