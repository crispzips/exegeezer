export const textItem = pgTable(
  "text_item",
  {
    textId: uuid("text_id")
      .notNull()
      .references(() => text_.id, { onDelete: "cascade" }),
    // 0-based place in the text (the paragraph's or header's `originalIndex`)
    position: integer("position").notNull(),
    // exactly one of these is set, matching the kind of item at this position
    paragraphId: uuid("paragraph_id").references(() => paragraph.id, { onDelete: "cascade" }),
    sectionId: uuid("section_id").references(() => section.id, { onDelete: "cascade" }),
    // sections only: header level in this text (1-6), and whether it is the Frontmatter (or, below, back matter)
    level: integer("level"),
    frontmatter: boolean("frontmatter").default(false).notNull(),
    // top-level sections only: whether the section is back matter (bibliography, appendices...)
    backmatter: boolean("backmatter").default(false).notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.textId, table.position] }),
    // which texts use a given paragraph or section
    index("text_item_paragraphId_idx").on(table.paragraphId),
    index("text_item_sectionId_idx").on(table.sectionId),
    check(
      "text_item_kind_check",
      sql`(${table.paragraphId} is not null and ${table.sectionId} is null and ${table.level} is null)
        or (${table.paragraphId} is null and ${table.sectionId} is not null and ${table.level} between 1 and 6)`,
    ),
  ],
);

// A comment is left on one or more paragraphs of a text (a comment on a section is a comment on all its paragraphs).
// Its words are a paragraph in a commentary on that text (so the commentary, a text in its own right, holds its
// comments); the `comment` row ties those words to the commentary, and `comment_paragraph` lists what they are about.
// Removing the words (or the commentary) removes the comment; removing a paragraph it is about drops only that tie.
export const comment = pgTable(
  "comment",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // the commentary (a text) this comment is part of
    commentaryId: uuid("commentary_id")
      .notNull()
      .references(() => text_.id, { onDelete: "cascade" }),
    // the comment itself: a paragraph in the commentary
    bodyParagraphId: uuid("body_paragraph_id")
      .notNull()
      .references(() => paragraph.id, { onDelete: "cascade" })
      .unique(),
    createdAt: timestamp("created_at").defaultNow().notNull(),
  },
  (table) => [index("comment_commentaryId_idx").on(table.commentaryId)],
);

// the paragraphs a comment is about, in the text its commentary is on
export const commentParagraph = pgTable(
  "comment_paragraph",
  {
    commentId: uuid("comment_id")
      .notNull()
      .references(() => comment.id, { onDelete: "cascade" }),
    paragraphId: uuid("paragraph_id")
      .notNull()
      .references(() => paragraph.id, { onDelete: "cascade" }),
  },
  (table) => [
    primaryKey({ columns: [table.commentId, table.paragraphId] }),
    index("comment_paragraph_paragraphId_idx").on(table.paragraphId),
  ],
);

