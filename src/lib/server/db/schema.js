// ---------------------------------------------------------------------------
// Texts. A paragraph or a section is a piece of content in its own right and can
// appear in any number of texts (remixes, and later commentaries, glosses...).
// A text is an assemblage of them: `text_item` arranges them, one row per place in
// the text, numbered from 0 in document order. What is specific to a place rather
// than to the content lives on that row: a section's header `level` (1-6) and
// whether it is the autogenerated Frontmatter. A section runs until the next
// section of the same or a shallower level, so the ordered rows are all it takes to
// rebuild a text's hierarchy.
// ---------------------------------------------------------------------------

export const text_ = pgTable(
  "text",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // null = not tied to an account
    userId: text("user_id").references(() => user.id, { onDelete: "cascade" }),
    title: text("title").notNull().default("Untitled"),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .defaultNow()
      .$onUpdate(() => /* @__PURE__ */ new Date())
      .notNull(),
  },
  (table) => [index("text_userId_idx").on(table.userId)],
);

export const paragraph = pgTable("paragraph", {
  id: uuid("id").primaryKey().defaultRandom(),
  body: text("body").notNull(),
});

export const section = pgTable("section", {
  id: uuid("id").primaryKey().defaultRandom(),
  title: text("title").notNull(),
});

export const textItem = pgTable(
  "text_item",
  {
    textId: uuid("text_id")
      .notNull()
      .references(() => text_.id, { onDelete: "cascade" }),
    // 0-based place in the text (the paragraph's or header's `originalIndex`)
    position: integer("position").notNull(),
    // exactly one of these is set, matching the kind of item at this position
    paragraphId: uuid("paragraph_id").references(() => paragraph.id, { onDelete: "cascade" }),
    sectionId: uuid("section_id").references(() => section.id, { onDelete: "cascade" }),
    // sections only: header level in this text (1-6), and whether it is the Frontmatter
    level: integer("level"),
    frontmatter: boolean("frontmatter").default(false).notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.textId, table.position] }),
    // which texts use a given paragraph or section
    index("text_item_paragraphId_idx").on(table.paragraphId),
    index("text_item_sectionId_idx").on(table.sectionId),
    check(
      "text_item_kind_check",
      sql`(${table.paragraphId} is not null and ${table.sectionId} is null and ${table.level} is null)
        or (${table.paragraphId} is null and ${table.sectionId} is not null and ${table.level} between 1 and 6)`,
    ),
  ],
);

export const textRelations = relations(text_, ({ one, many }) => ({
  user: one(user, { fields: [text_.userId], references: [user.id] }),
  items: many(textItem),
}));

export const paragraphRelations = relations(paragraph, ({ many }) => ({ items: many(textItem) }));
export const sectionRelations = relations(section, ({ many }) => ({ items: many(textItem) }));

export const textItemRelations = relations(textItem, ({ one }) => ({
  text: one(text_, { fields: [textItem.textId], references: [text_.id] }),
  paragraph: one(paragraph, { fields: [textItem.paragraphId], references: [paragraph.id] }),
  section: one(section, { fields: [textItem.sectionId], references: [section.id] }),
}));
