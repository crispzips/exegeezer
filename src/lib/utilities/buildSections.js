/**
 * Turn a flat list of paragraphs into a tree of sections.
 *
 * A section is a data entity of its own: a header plus a one-dimensional array of
 * `children`, each of which is either a paragraph or another section. A section
 * ends at the next header of the same or a higher level (smaller number), so a
 * "##" section holds the "###" sections beneath it. Paragraphs before the first
 * header stay at the top level.
 *
 * @typedef {{ id: string, originalIndex: number, text: string, level?: number, frontmatter?: boolean, backmatter?: boolean }} Paragraph
 * @typedef {{ kind: 'paragraph', paragraph: Paragraph, paragraphIndex: number }} ParagraphNode
 * @typedef {{ kind: 'section', id: string, sectionIndex: number, hierarchicalIndex: string, level: number, title: string, header: Paragraph, children: SectionChild[] }} Section
 * @typedef {ParagraphNode | Section} SectionChild
 *
 * Besides the index every paragraph shares (`originalIndex`, headers included), sections
 * and paragraphs each get their own 1-based running index in document order:
 * `sectionIndex` counts headers, `hierarchicalIndex` numbers a section among its siblings
 * and joins the numbers down from the top with periods ("2.4.3" is the third subsection of
 * the fourth section of the second top-level section; an autogenerated Frontmatter section is "0", so real
 * chapters still start at 1), `paragraphIndex` counts body paragraphs only.
 *
 * @param {Paragraph[]} paragraphs
 * @returns {SectionChild[]} the top-level nodes
 */
export function buildSections(paragraphs) {
	/** @type {SectionChild[]} */
	const root = [];
	/** @type {Section[]} open sections, outermost first */
	const stack = [];
	let sectionCount = 0;
	let paragraphCount = 0;
	let rootSections = 0;
	/** @type {Map<Section, number>} sections counted so far inside each section */
	const childSections = new Map();

	for (const paragraph of paragraphs) {
		const level = paragraph.level ?? 0;

		if (level > 0) {
			// close every open section that this header ends
			while (stack.length && stack[stack.length - 1].level >= level) stack.pop();
			const parent = stack.length ? stack[stack.length - 1] : null;
			let n;
			if (parent) {
				n = (childSections.get(parent) ?? 0) + 1;
				childSections.set(parent, n);
			} else n = paragraph.frontmatter ? 0 : ++rootSections; // autogenerated Frontmatter is chapter 0
			/** @type {Section} */
			const section = {
				kind: 'section',
				id: paragraph.id,
				sectionIndex: ++sectionCount,
				hierarchicalIndex: parent ? `${parent.hierarchicalIndex}.${n}` : String(n),
				level,
				title: paragraph.text.replace(/^#{1,6}\s+/, ''),
				header: paragraph,
				children: []
			};
			(stack.length ? stack[stack.length - 1].children : root).push(section);
			stack.push(section);
		} else {
			(stack.length ? stack[stack.length - 1].children : root).push({ kind: 'paragraph', paragraph, paragraphIndex: ++paragraphCount });
		}
	}
	return root;
}
